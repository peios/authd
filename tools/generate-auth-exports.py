"""Generate C declarations and private Rust bindings from the exported functions."""

import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def snake(name: str) -> str:
    """Convert a Rust ABI type name to the public C spelling."""
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


PRIMITIVES = {
    "u8": "uint8_t",
    "u32": "uint32_t",
    "u64": "uint64_t",
    "i16": "int16_t",
    "i32": "int32_t",
    "i64": "int64_t",
    "usize": "size_t",
    "()": "void",
}


def c_type(value: str) -> str:
    """Translate the exported Rust type subset without changing constness."""
    if value.startswith("*const "):
        return "const " + c_type(value[7:]) + " *"
    if value.startswith("*mut "):
        return c_type(value[5:]) + " *"
    return PRIMITIVES.get(value, "peios_auth_" + snake(value))


def c_declaration(value: str, name: str) -> str:
    """Place a pointer star beside its declarator, as PSC requires."""
    kind = c_type(value)
    return kind + ("" if kind.endswith("*") else " ") + name


def declarations(name: str, arguments: str, result: str) -> tuple[str, str]:
    """Render one public signature in C and Rust without altering its types."""
    args = []
    rust_args = []
    for argument in arguments.split(","):
        if not argument.strip():
            continue
        field, value = argument.strip().split(":", 1)
        value = value.strip()
        args.append(c_declaration(value, field))
        rust_args.append(field + ": " + value)
    declaration = c_declaration(result, name) + "(" + (", ".join(args) or "void") + ");"
    if len(declaration) > 100:
        declaration = c_declaration(result, name) + "(\n    " + ",\n    ".join(args) + "\n);"
    rust = "    pub fn " + name + "(" + ", ".join(rust_args) + ") -> " + result + ";"
    return declaration, rust


def main() -> None:
    """Regenerate declarations and exports from the two owned ABI modules."""
    header = [
        "/* Generated by tools/generate-auth-exports.py. */",
        "#ifndef PEIOS_AUTH_FUNCTIONS_H",
        "#define PEIOS_AUTH_FUNCTIONS_H",
    ]
    rust = [
        "//! Generated private declarations; use the safe wrapper.",
        "use auth_abi::*;",
        "pub enum Client {}",
        "pub enum Operation {}",
        '#[link(name = "auth")]',
        'unsafe extern "C" {',
    ]
    exports = []
    for source in ["api.rs", "results.rs"]:
        text = (ROOT / "libauth/src" / source).read_text()
        pattern = (
            r'pub (?:unsafe )?extern "C" fn (peios_auth_\w+)\((.*?)\)(?:\s*->\s*([^\{]+))?\s*\{'
        )
        for match in re.finditer(pattern, text, re.S):
            name, arguments, result = match.groups()
            result = (result or "()").strip()
            c_declaration, rust_declaration = declarations(name, arguments, result)
            header.append(c_declaration)
            rust.append(rust_declaration)
            exports.append(name)
    header.append("#endif")
    rust.append("}")
    (ROOT / "libauth/include/peios/auth-functions.h").write_text("\n".join(header) + "\n")
    (ROOT / "peios-auth/src/sys.rs").write_text("\n".join(rust) + "\n")
    (ROOT / "libauth/exports.txt").write_text("\n".join(sorted(exports)) + "\n")

    subprocess.run(
        [
            "rustfmt",
            "--config-path",
            str(ROOT / "tools/rustfmt.toml"),
            str(ROOT / "peios-auth/src/sys.rs"),
        ],
        check=True,
    )

    subprocess.run(
        [
            "clang-format",
            "--style=file:" + str(ROOT / "tools/clang-format.yaml"),
            "-i",
            str(ROOT / "libauth/include/peios/auth-functions.h"),
        ],
        check=True,
    )


if __name__ == "__main__":
    main()
