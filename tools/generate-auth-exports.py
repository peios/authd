"""Generate C declarations and private Rust bindings from the exported functions."""
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()
primitives = {"u8": "uint8_t", "u32": "uint32_t", "u64": "uint64_t", "i16": "int16_t", "i32": "int32_t", "i64": "int64_t", "usize": "size_t", "()": "void"}

def c_type(value):
    if value.startswith("*const "):
        return "const " + c_type(value[7:]) + " *"
    if value.startswith("*mut "):
        return c_type(value[5:]) + " *"
    return primitives.get(value, "peios_auth_" + snake(value))

header = ["/* Generated by tools/generate-auth-exports.py. */", "#ifndef PEIOS_AUTH_FUNCTIONS_H", "#define PEIOS_AUTH_FUNCTIONS_H"]
rust = ["//! Generated private declarations; use the safe wrapper.", "use auth_abi::*;", "pub enum Client {}", "pub enum Operation {}", '#[link(name = "auth")]', 'unsafe extern "C" {']
exports = []
for source in ["api.rs", "results.rs"]:
    text = (ROOT / "libauth/src" / source).read_text()
    pattern = r'pub (?:unsafe )?extern "C" fn (peios_auth_\w+)\((.*?)\)(?:\s*->\s*([^\{]+))?\s*\{'
    for match in re.finditer(pattern, text, re.S):
        name, arguments, result = match.groups()
        result = (result or "()").strip()
        args = []
        rust_args = []
        for argument in arguments.split(","):
            if not argument.strip():
                continue
            field, value = argument.strip().split(":", 1)
            value = value.strip()
            args.append(c_type(value) + " " + field)
            rust_args.append(field + ": " + value)
        declaration = c_type(result) + " " + name + "(" + (", ".join(args) or "void") + ");"
        if len(declaration) > 100:
            declaration = c_type(result) + " " + name + "(\n    " + ",\n    ".join(args) + "\n);"
        header.append(declaration)
        rust.append("    pub fn " + name + "(" + ", ".join(rust_args) + ") -> " + result + ";")
        exports.append(name)
header.append("#endif")
rust.append("}")
(ROOT / "libauth/include/peios/auth-functions.h").write_text("\n".join(header) + "\n")
(ROOT / "peios-auth/src/sys.rs").write_text("\n".join(rust) + "\n")
(ROOT / "libauth/exports.txt").write_text("\n".join(sorted(exports)) + "\n")

subprocess.run(["rustfmt", "--config-path", str(ROOT / "tools/rustfmt.toml"), str(ROOT / "peios-auth/src/sys.rs")], check=True)
